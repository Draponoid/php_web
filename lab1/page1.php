<?php
// ЛР А-1: Конвертация статического контента в динамический
// Переменная с названием страницы (требование: хранится в переменной)
$page_title = "Иванов И.И., гр. ВЕБ-11 — ЛР А-1: Главная";

// Массив пунктов меню: ['url', 'текст', 'активен на этой странице?']
$menu = [
    ['page1.php', 'Главная',     true],
    ['page2.php', 'О проекте',   false],
    ['page3.php', 'Контакты',    false],
];

// Фотографии меняются в зависимости от чётности секунды
$photo_num = date('s') % 2 + 1;   // 1 или 2
?>
<!DOCTYPE html>
<html lang="ru">
<head>
    <meta charset="UTF-8">
    <title><?php echo $page_title; ?></title>
    <link rel="stylesheet" href="styles.css">
</head>
<body>

<header>
    <?php foreach ($menu as $item): ?>
        <a href="<?php echo $item[0]; ?>"
           <?php if ($item[2]) echo 'class="active"'; ?>>
           <?php echo $item[1]; ?>
        </a>
    <?php endforeach; ?>
</header>

<main>
    <h1>Добро пожаловать</h1>

    <h2>Фотография (меняется каждую секунду)</h2>
    <img class="photo" src="fotos/foto<?php echo $photo_num; ?>.jpg" alt="Фото">

    <h2>Таблица данных</h2>
    <table>
        <!-- Первая строка целиком выводится через PHP -->
        <?php echo '<tr><th>№</th><th>Параметр</th><th>Значение</th></tr>'; ?>
        <tr>
            <td>1</td>
            <!-- Содержимое ячеек второй строки выводится через PHP -->
            <td><?php echo 'Язык программирования'; ?></td>
            <td><?php echo 'PHP'; ?></td>
        </tr>
        <tr>
            <td>2</td>
            <td><?php echo 'Версия'; ?></td>
            <td><?php echo '8.x'; ?></td>
        </tr>
    </table>

    <h2>О PHP</h2>
    <p>PHP (Hypertext Preprocessor) — серверный язык программирования, широко применяемый для создания
       динамических веб-страниц. Основная задача PHP — формировать HTML-код страницы на сервере
       непосредственно перед его отправкой браузеру. Это позволяет делать страницы уникальными
       для каждого пользователя и каждого момента времени.</p>
    <p>В отличие от статических HTML-страниц, PHP-страницы могут отображать текущее время,
       результаты вычислений, данные из базы данных и многое другое.</p>
</main>

<footer>
    Сформировано <?php echo date('d.m.Y в H:i:s'); ?>
</footer>

</body>
</html>
